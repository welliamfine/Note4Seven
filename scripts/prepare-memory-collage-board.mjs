import { access, mkdir, writeFile } from 'node:fs/promises';
import { extname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = fileURLToPath(new URL('..', import.meta.url));
const designBoardRoot = resolve(root, 'design/board');
const artifactsRoot = resolve(root, 'artifacts');
const migrationsRoot = resolve(root, 'server/migrations');
const editableBounds = Object.freeze({ left: 0.045, top: 0.13, right: 0.955, bottom: 0.945 });
const sourceFrame = Object.freeze({ left: 119, top: 44, right: 902, bottom: 945 });

const args = Object.fromEntries(process.argv.slice(2).map((value) => {
  const separator = value.indexOf('=');
  return separator > 2 ? [value.slice(2, separator), value.slice(separator + 1)] : [value.slice(2), ''];
}));

if (!args.source || !args['asset-key'] || !args.migration || !args.name) {
  throw new Error('Usage: node scripts/prepare-memory-collage-board.mjs --source=design/board/<file>.png --asset-key=board-08 --name=<name> --migration=server/migrations/NNN_add_<key>.sql [--category=default] [--sort-order=7]');
}

const sourcePath = resolve(root, args.source);
const migrationPath = resolve(root, args.migration);
const assetKey = args['asset-key'];
const category = args.category || 'default';
const sortOrder = Number(args['sort-order'] ?? 0);

assertInside(sourcePath, designBoardRoot, 'Board source');
assertInside(migrationPath, migrationsRoot, 'Migration');
if (extname(sourcePath).toLowerCase() !== '.png') throw new Error('Board source must be a PNG file');
if (!/^board-[a-z0-9][a-z0-9-]*$/.test(assetKey)) throw new Error(`Invalid stable asset key: ${assetKey}`);
if (!Number.isInteger(sortOrder) || sortOrder < 0) throw new Error('sort-order must be a non-negative integer');
await access(sourcePath);
try {
  await access(migrationPath);
  throw new Error(`Refusing to overwrite existing migration: ${relative(root, migrationPath)}`);
} catch (error) {
  if (error instanceof Error && error.message.startsWith('Refusing')) throw error;
  if (!error || typeof error !== 'object' || error.code !== 'ENOENT') throw error;
}

const metadata = await sharp(sourcePath).metadata();
if (metadata.width !== 1024 || metadata.height !== 1024) {
  throw new Error(`Board source must be 1024x1024, received ${metadata.width ?? 0}x${metadata.height ?? 0}`);
}
if (!metadata.hasAlpha) throw new Error('Board source must contain an alpha channel');
const alphaBounds = await alphaBoundsOf(sourcePath);
if (
  alphaBounds.left < sourceFrame.left
  || alphaBounds.top < sourceFrame.top
  || alphaBounds.right > sourceFrame.right
  || alphaBounds.bottom > sourceFrame.bottom
  || alphaBounds.right - alphaBounds.left < 700
  || alphaBounds.bottom - alphaBounds.top < 830
) {
  throw new Error(`Board artwork must fit the shared source frame ${JSON.stringify(sourceFrame)}, received ${JSON.stringify(alphaBounds)}`);
}

const cloudDirectory = 'memory-collage/boards';
const outputDirectory = resolve(artifactsRoot, 'memory-collage-board-import', assetKey, cloudDirectory);
const originalFileName = `${assetKey}.webp`;
const thumbnailFileName = `${assetKey}-thumb.webp`;
const originalPath = resolve(outputDirectory, originalFileName);
const thumbnailPath = resolve(outputDirectory, thumbnailFileName);
await mkdir(outputDirectory, { recursive: true });
await sharp(sourcePath).ensureAlpha().webp({ quality: 92, alphaQuality: 100, effort: 5 }).toFile(originalPath);
await sharp(sourcePath)
  .ensureAlpha()
  .resize({ width: 360, height: 360, fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .webp({ quality: 92, alphaQuality: 100, effort: 5 })
  .toFile(thumbnailPath);

const originalFileKey = `${cloudDirectory}/${originalFileName}`;
const thumbnailFileKey = `${cloudDirectory}/${thumbnailFileName}`;
await mkdir(resolve(migrationPath, '..'), { recursive: true });
await writeFile(migrationPath, `${[
  '-- Generated by scripts/prepare-memory-collage-board.mjs. Do not edit asset bounds.',
  'INSERT INTO memory_collage_board_asset',
  '  (asset_key, name, category, thumbnail_file_key, original_file_key, width, height, editable_left, editable_top, editable_right, editable_bottom, status, sort_order)',
  'VALUES',
  `  (${sql(assetKey)}, ${sql(args.name)}, ${sql(category)}, ${sql(thumbnailFileKey)}, ${sql(originalFileKey)}, 1024, 1024, ${decimal(editableBounds.left)}, ${decimal(editableBounds.top)}, ${decimal(editableBounds.right)}, ${decimal(editableBounds.bottom)}, 'active', ${sortOrder})`,
  'ON DUPLICATE KEY UPDATE',
  '  name = VALUES(name), category = VALUES(category),',
  '  thumbnail_file_key = VALUES(thumbnail_file_key), original_file_key = VALUES(original_file_key),',
  '  width = VALUES(width), height = VALUES(height),',
  '  editable_left = VALUES(editable_left), editable_top = VALUES(editable_top),',
  '  editable_right = VALUES(editable_right), editable_bottom = VALUES(editable_bottom),',
  "  status = 'active', sort_order = VALUES(sort_order);",
  '',
].join('\n')}\n`, 'utf8');

const manifest = {
  schemaVersion: 1,
  assetKey,
  source: relative(root, sourcePath).replaceAll('\\', '/'),
  sourceFrame,
  editableBounds,
  uploads: [
    { localPath: relative(root, originalPath).replaceAll('\\', '/'), cloudFileKey: originalFileKey },
    { localPath: relative(root, thumbnailPath).replaceAll('\\', '/'), cloudFileKey: thumbnailFileKey },
  ],
  migration: relative(root, migrationPath).replaceAll('\\', '/'),
};
await writeFile(resolve(outputDirectory, 'import-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
process.stdout.write(`${JSON.stringify(manifest, null, 2)}\n`);

function assertInside(target, parent, label) {
  if (target !== parent && !target.startsWith(`${parent}${sep}`)) {
    throw new Error(`${label} must stay inside ${relative(root, parent)}`);
  }
}

async function alphaBoundsOf(filePath) {
  const { data, info } = await sharp(filePath).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let left = info.width;
  let top = info.height;
  let right = 0;
  let bottom = 0;
  for (let y = 0; y < info.height; y += 1) {
    for (let x = 0; x < info.width; x += 1) {
      if (data[(y * info.width + x) * 4 + 3] <= 8) continue;
      left = Math.min(left, x);
      top = Math.min(top, y);
      right = Math.max(right, x + 1);
      bottom = Math.max(bottom, y + 1);
    }
  }
  if (!right || !bottom) throw new Error('Board source has no visible pixels');
  return { left, top, right, bottom };
}

function sql(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function decimal(value) {
  return value.toFixed(6);
}
